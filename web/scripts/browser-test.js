import { chromium, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';
import { once } from 'node:events';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createApp } from '../backend/app.js';
import { query, pool } from '../backend/db.js';
import { hashPassword } from '../backend/security.js';
import { saveClient } from '../backend/service.js';

const suffix = randomBytes(5).toString('hex');
const user = `Prueba Navegador ${suffix}`, clientEmail = `browser-${suffix}@example.test`;
let browser, server, adminId, clientId;
try {
  const result = await query('INSERT INTO web_usuarios (usuario, rol, password_hash) VALUES (?, ?, ?)', [user, 'administrador', await hashPassword('prueba123')]);
  adminId = result.insertId;
  clientId = (await saveClient(null, { nombre: 'Cliente Navegador', cedula: `QN-${suffix}`, correo: clientEmail, password: 'cliente123', direccion: 'Barrio Central', monto: '0' }, { id: adminId, rol: 'administrador' })).id;
  server = createApp().listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(), errors = [];
  page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/login-desktop.png', fullPage: true });
  await page.getByLabel('Usuario o correo').fill(user);
  await page.getByLabel('Contraseña', { exact: true }).fill('prueba123');
  await page.getByRole('button', { name: 'Ingresar al sistema' }).click();
  await expect(page.getByRole('heading', { name: 'Resumen', exact: true })).toBeVisible();
  for (const name of ['Clientes', 'Préstamos', 'Solicitudes', 'Citas', 'Usuarios y roles', 'Reportes']) {
    await page.getByRole('navigation').getByRole('button', { name: new RegExp(`^${name}(?: \\d+)?$`) }).click();
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  }
  await page.getByRole('navigation').getByRole('button', { name: 'Préstamos', exact: true }).click();
  await page.getByRole('button', { name: 'Nuevo préstamo', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Cliente', { exact: true }).selectOption(String(clientId));
  await dialog.getByLabel('Capital (C$)', { exact: true }).fill('1000');
  await dialog.getByLabel('Número de cuotas').fill('2');
  await dialog.getByRole('button', { name: 'Ver distribución de cuotas' }).click();
  await expect(dialog.getByRole('cell', { name: /575/ })).toHaveCount(2);
  await dialog.getByRole('button', { name: 'Guardar préstamo', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('textbox', { name: 'Buscar registros' }).fill(`QN-${suffix}`);
  const row = page.getByRole('row').filter({ hasText: `QN-${suffix}` });
  await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'Ver cuotas' }).click();
  await expect(dialog.getByRole('heading', { name: /Cliente Navegador/ })).toBeVisible();
  await dialog.getByLabel('Monto del abono (C$)').fill('575');
  await dialog.getByRole('button', { name: 'Registrar abono', exact: true }).click();
  await expect(dialog.getByText('Abono registrado.', { exact: false })).toBeVisible();
  const receiptPath = await dialog.getByRole('link', { name: 'Descargar recibo PDF' }).getAttribute('href');
  const pdf = await context.request.get(`${base}${receiptPath}`);
  assert.equal(pdf.status(), 200); assert.equal((await pdf.body()).subarray(0, 5).toString(), '%PDF-');
  await page.screenshot({ path: 'test-results/prestamo-desktop.png', fullPage: true });
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('Usuario o correo').fill(clientEmail);
  await page.getByLabel('Contraseña', { exact: true }).fill('cliente123');
  await page.getByRole('button', { name: 'Ingresar al sistema' }).click();
  await expect(page.getByRole('heading', { name: 'Resumen', exact: true })).toBeVisible();
  await expect(page.getByRole('navigation').getByRole('button', { name: 'Usuarios y roles' })).toHaveCount(0);
  await page.getByRole('navigation').getByRole('button', { name: 'Mi dirección', exact: true }).click();
  await expect(page.locator('.leaflet-container')).toBeVisible();
  await page.getByLabel('Dirección', { exact: true }).fill('Dirección de prueba');
  await page.getByLabel('Latitud', { exact: true }).fill('12.1364');
  await page.getByLabel('Longitud', { exact: true }).fill('-86.2514');
  await page.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Dirección y ubicación guardadas.' })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Mis préstamos', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Mis préstamos', exact: true })).toBeVisible();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'La página no debe desbordarse en móvil.');
  await page.screenshot({ path: 'test-results/cliente-mobile.png', fullPage: true });
  await page.getByRole('navigation').getByRole('button', { name: 'Mis citas', exact: true }).click();
  await page.getByRole('button', { name: 'Agendar cita', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Agendar cita', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Cita agendada.' })).toBeVisible();
  assert.deepEqual(errors, [], 'El navegador no debe registrar errores de JavaScript.');
  console.log('Navegador OK: login, navegación por módulos, préstamo al 15%, simulación, abono, PDF, vista móvil, mapa y cita.');
} finally {
  if (browser) await browser.close();
  if (server) await new Promise(resolve => server.close(resolve));
  if (clientId) {
    await query('DELETE p FROM pagos_prestamo p JOIN prestamo l ON l.id = p.prestamo_id WHERE l.cliente_id = ?', [clientId]);
    await query('DELETE t FROM web_prestamo_tasas t JOIN prestamo l ON l.id = t.prestamo_id WHERE l.cliente_id = ?', [clientId]);
    await query('DELETE FROM prestamo WHERE cliente_id = ?', [clientId]);
    await query('DELETE FROM solicitudes_prestamo WHERE cliente_id = ?', [clientId]);
    await query('DELETE FROM citas WHERE cliente_id = ?', [clientId]);
    await query('DELETE FROM web_asignaciones WHERE cliente_id = ?', [clientId]);
    await query('DELETE FROM clientes WHERE id = ? AND correo = ?', [clientId, clientEmail]);
  }
  if (adminId) await query('DELETE FROM web_usuarios WHERE id = ? AND usuario = ?', [adminId, user]);
  await pool.end();
}
